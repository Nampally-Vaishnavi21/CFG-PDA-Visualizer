"""Regenerate diagrams, transition tables and worked traces from the code.

    python scripts/build_assets.py

Writes diagrams/*.dot (and *.png when Graphviz `dot` is installed),
docs/transition_tables.md and docs/worked_examples.md.
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pda import arithmetic, balanced, palindrome      # noqa: E402

BAL, ARI, PAL = balanced.build_pda(), arithmetic.build_pda(), palindrome.build_pda()

# ------------------------------------------------------------------ diagrams
tokens, lexemes, _ = arithmetic.tokenize("2+3*4")
diagrams = {
    "balanced_pda": BAL.to_dot(),
    "arithmetic_pda": ARI.to_dot(),
    "palindrome_pda": PAL.to_dot(),
    "parse_tree_2_plus_3_times_4": arithmetic.tree_dot(arithmetic.parse_tree(ARI.search(tokens), lexemes)),
    "ambiguity_tree_1": arithmetic.AMBIGUITY_TREE_A,
    "ambiguity_tree_2": arithmetic.AMBIGUITY_TREE_B,
}
out = os.path.join(ROOT, "diagrams")
os.makedirs(out, exist_ok=True)
have_dot = shutil.which("dot") is not None
for name, dot in diagrams.items():
    path = os.path.join(out, name + ".dot")
    with open(path, "w", encoding="utf-8") as f:
        f.write(dot.replace('"transparent"', '"white"'))
    if have_dot:
        subprocess.run(["dot", "-Tpng", "-Gdpi=150", path, "-o", path[:-4] + ".png"], check=True)
print(f"{len(diagrams)} diagrams written (PNG: {'yes' if have_dot else 'no - install Graphviz'})")


def md_table(rows):
    head = list(rows[0])
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(str(r[h]).replace("|", "\\|") for h in head) + " |" for r in rows]
    return "\n".join(lines)


# ------------------------------------------------------------------ transition tables
parts = ["# PDA Transition Tables",
         "_Generated by `scripts/build_assets.py` from the PDA objects used by the application._\n",
         "Notation: δ(q, a, X) ∋ (p, γ) — in state q, reading a (ε = no input), with X on top, "
         "go to p and replace X by γ (leftmost symbol of γ on top).\n"]
for title, pda in [("Balanced-brackets DPDA", BAL), ("Arithmetic-expression PDA (from G3)", ARI),
                   ("Palindrome NPDA", PAL)]:
    parts.append(f"## {title}\n")
    parts.append(f"Q = {{{', '.join(pda.states)}}}, Σ = {{{', '.join(pda.input_alphabet)}}}, "
                 f"Γ = {{{', '.join(pda.stack_alphabet)}}}, q0 = {pda.start}, "
                 f"F = {{{', '.join(sorted(pda.finals))}}}. "
                 f"Deterministic: **{'yes' if pda.is_deterministic() else 'no'}**. "
                 f"{len(pda.rules)} transitions.\n")
    parts.append(md_table(pda.transition_rows()) + "\n")
with open(os.path.join(ROOT, "docs", "transition_tables.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(parts))


# ------------------------------------------------------------------ worked examples
def trace(pda, result, sep):
    index = result.best_index()
    rows = []
    for i, node in enumerate(result.path(index)):
        rows.append({"Step": i, "State": node.state,
                     "Remaining input": sep.join(result.tokens[node.pos:]) or "ε",
                     "Stack (top → bottom)": " ".join(node.stack),
                     "Move": node.rule.formal() if node.rule else "start",
                     "Stack operation": node.rule.operation() if node.rule else "—"})
    return md_table(rows), index


def derivation(grammar, tokens):
    steps, result = grammar.derive(tokens)
    if steps is None:
        form, pos, why = grammar.failed_derivation(result)
        return (f"No derivation exists. Furthest attempt matched {pos} of {len(tokens)} symbols, "
                f"reaching the sentential form `{' '.join(form) or 'ε'}`. {why}")
    return "`" + " ⇒ ".join(" ".join(f) or "ε" for f, _ in steps) + "`"


doc = ["# Worked Examples (generated)",
       "_Generated by `scripts/build_assets.py` by running the simulator. Nothing here is typed by hand._\n"]


def section(title, pda, grammar, text, tokens, sep, explain, extra=None):
    result = pda.search(tokens)
    table, index = trace(pda, result, sep)
    doc.append(f"### Input `{text or 'ε'}` — {'ACCEPTED' if result.accepted else 'REJECTED'}\n")
    doc.append(f"**Stack trace** ({len(result.nodes)} configurations explored)\n")
    doc.append(table + "\n")
    if not result.accepted:
        doc.append(f"**Why it stops:** {result.why_stuck(index)} {explain(result)}\n")
    doc.append(f"**Derivation in {grammar.name}:** {derivation(grammar, tokens)}\n")
    if extra:
        doc.append(extra(result))


doc.append("## 1. Balanced brackets\n")
for text in ["([]{})", "([)]", "(()"]:
    section("bal", BAL, balanced.GRAMMAR, text, list(text), "", balanced.explain)

doc.append("## 2. Arithmetic expressions\n")
for text in ["2+3*4", "(2+3)*4", "2+*3", "(2+3"]:
    toks, lex, _ = arithmetic.tokenize(text)
    section("ari", ARI, arithmetic.GRAMMAR, text, toks, " ", arithmetic.explain)

doc.append("## 3. Palindromes\n")
for text in ["0110", "010", "0111"]:
    section("pal", PAL, palindrome.GRAMMAR, text, list(text), "", palindrome.explain,
            lambda r: "**All nondeterministic branches**\n\n" + md_table(palindrome.branches(r)) + "\n")

with open(os.path.join(ROOT, "docs", "worked_examples.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(doc))
print("docs/transition_tables.md and docs/worked_examples.md written")
